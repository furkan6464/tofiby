function overlay(speckles: string) {
  const shell = parseFrame(SHELL);
  const marks = parseFrame(speckles);
  return shell.map((row, y) =>
    row.map((cell, x) => (marks[y][x] === "speckle" ? "speckle" : cell)),
  );
}

